-- 20260909_menu_items_is_hidden.sql
--
-- แยก "หมดวันนี้" ออกจาก "เลิกขายแล้ว"
--
-- ปัญหาเดิม: ปุ่ม "ลบ" ในหน้าร้านกดแล้วเงียบ เพราะฐานข้อมูลห้ามลบเมนูที่เคยมี
-- คนสั่ง (order_items อ้างถึงอยู่ ด้วย on delete no action ซึ่งกันประวัติการขายหาย)
-- แต่โค้ดหน้าร้านไม่ตรวจ error ร้านจึงกดปุ่ม เมนูไม่หาย และไม่มีอะไรบอกว่าทำไม
-- ตอนนี้มีเมนู 17 รายการ ในนั้น 4 รายการลบไม่ได้ และร้านไม่มีทางรู้ว่าอันไหน
--
-- ทำไมไม่ใช้ is_available ที่มีอยู่แล้ว: หน้าลูกค้ากรอง is_available = true อยู่แล้ว
-- เมนูที่กด "หมด" จึงหายจากสายตาลูกค้าเหมือนกัน — แต่สองอย่างนี้ต่างกันสำหรับ "ร้าน"
--   หมด        = วันนี้ของหมด พรุ่งนี้เอากลับมาขาย ต้องยังเห็นในรายการเพื่อไม่ลืมเปิด
--   เลิกขาย    = ไม่ขายแล้ว ขอให้พ้นสายตาไปเลย ไม่งั้นรายการรกขึ้นเรื่อย ๆ ตลอดไป
-- ถ้ารวมสองอย่างเป็นช่องเดียว เมนูที่เลิกขายแล้วจะปนอยู่กับเมนูที่แค่หมดวันนี้
--
-- คอลัมน์นี้เพิ่มอย่างเดียว ไม่แก้ข้อมูลเดิม แถวที่มีอยู่ได้ false ทั้งหมด
-- แผนกู้: เลิกอ่านคอลัมน์นี้ในโค้ด ปล่อยคอลัมน์ทิ้งไว้ก่อน (กฎ ๖.๖.๔ สองจังหวะ)

alter table public.menu_items
  add column if not exists is_hidden boolean not null default false;

comment on column public.menu_items.is_hidden is
  'ร้านเลิกขายเมนูนี้แล้ว — ต่างจาก is_available ที่แปลว่าหมดชั่วคราว';

-- ดัชนีนี้ช่วยหน้าลูกค้าที่ดึงเฉพาะเมนูที่ยังขายอยู่ของร้านหนึ่ง
create index if not exists menu_items_visible_idx
  on public.menu_items (merchant_id)
  where not is_hidden;

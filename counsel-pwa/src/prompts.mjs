// พรอมต์ counsel ในฐานข้อมูลสั่งให้ใส่รหัส [P#]/[S#] ท้ายทุกประโยค (ระบบ LINE ลบให้ทีหลัง)
// แต่เสียงลบทีหลังไม่ได้ และสั่งห้ามแล้ว Gemini ยังหลุด จึงตัดเรื่องรหัสออกก่อนส่งให้ Gemini เลย
export function voiceCounselPrompt(prompt) {
  return String(prompt)
    .split("\n")
    .filter((line) => !/รหัส|\[P#\]|\[S#\]/.test(line))
    .join("\n")
    .replace(/\n*แบบคำตอบ:[\s\S]*$/, "")
    .replace(/\[P\d\]\s*/g, "")
    .replace(/หลัก P1-P6/g, "หลักทั้ง 6 ข้อ")
    .trim();
}

